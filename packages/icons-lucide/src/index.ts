export function getLucideIconName(name: IconName): LucideIconName {
    return LucideIconNames[name];
}

export async function loadLucideIcon(name: IconName): Promise<LucideIconData> {
    const module = await lucideDynamicIconImports[getLucideIconName(name)]();
    return module.default;
}

export async function getLucideSvg(name: IconName, params?: LucideBuildParams): Promise<string> {
    return buildLucideSvg(await loadLucideIcon(name), params);
}

